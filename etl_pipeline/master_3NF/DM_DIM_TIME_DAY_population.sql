-- ============================================================
-- SCHEMA: BL_DM
-- TABLE:  DIM_TIME_DAY
-- SCD Type 0 - populated once, never updated
-- ============================================================

-- Create schema
CREATE SCHEMA IF NOT EXISTS BL_DM;

-- Drop table and sequence
DROP TABLE    IF EXISTS BL_DM.DIM_TIME_DAY;
DROP SEQUENCE IF EXISTS BL_DM.SEQ_DIM_TIME_DAY;

-- Create sequence for surrogate key
CREATE SEQUENCE BL_DM.SEQ_DIM_TIME_DAY
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;

-- Create table
CREATE TABLE BL_DM.DIM_TIME_DAY (
    DATE_SURR_ID      BIGINT        NOT NULL DEFAULT NEXTVAL('BL_DM.SEQ_DIM_TIME_DAY'),
    DATE_SRC_ID       VARCHAR(8)    NOT NULL,   -- NK: YYYYMMDD
    FULL_DT           DATE          NOT NULL,
    DAY_OF_WEEK_NUM   INTEGER       NOT NULL,   -- 1=Monday, 7=Sunday (ISO)
    DAY_OF_WEEK_DESC  VARCHAR(25)   NOT NULL,
    IS_WEEKEND        INTEGER       NOT NULL,   -- 1=weekend, 0=weekday
    DAY_OF_MONTH_NUM  INTEGER       NOT NULL,
    WEEK_NUM          INTEGER       NOT NULL,   -- ISO week number
    MONTH_NUM         CHAR(2)       NOT NULL,   -- '01'-'12'
    MONTH_DESC        VARCHAR(25)   NOT NULL,
    QUARTER_NUM       CHAR(1)       NOT NULL,   -- '1'-'4'
    YEAR_NUM          CHAR(4)       NOT NULL,
    TA_INSERT_DT      DATE          NOT NULL,   -- TA_ prefix: technical column
    SOURCE_SYSTEM     VARCHAR(50)   NOT NULL,
    SOURCE_ENTITY     VARCHAR(50)   NOT NULL,
    CONSTRAINT PK_DIM_TIME_DAY        PRIMARY KEY (DATE_SURR_ID),
    CONSTRAINT UQ_DIM_TIME_DAY_NK     UNIQUE      (DATE_SRC_ID)
);

-- Comments
COMMENT ON TABLE  BL_DM.DIM_TIME_DAY IS
    'Calendar date dimension - SCD Type 0. Populated once, never updated. Source: MANUAL.';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.DATE_SURR_ID     IS 'Surrogate PK - generated by sequence SEQ_DIM_TIME_DAY';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.DATE_SRC_ID      IS 'Natural key - date formatted as YYYYMMDD string';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.FULL_DT          IS 'Actual calendar date';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.DAY_OF_WEEK_NUM  IS '1=Monday through 7=Sunday (ISO)';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.DAY_OF_WEEK_DESC IS 'Full day name: Monday - Sunday';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.IS_WEEKEND       IS '1 if Saturday or Sunday, 0 otherwise';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.DAY_OF_MONTH_NUM IS 'Day number within the month: 1-31';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.WEEK_NUM         IS 'ISO 8601 week number: 1-53';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.MONTH_NUM        IS 'Zero-padded month number: 01-12';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.MONTH_DESC       IS 'Full month name: January - December';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.QUARTER_NUM      IS 'Quarter of year: 1-4';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.YEAR_NUM         IS 'Four-digit year: YYYY';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.TA_INSERT_DT     IS 'Technical: row creation date (TA_ prefix per Naming Conventions)';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.SOURCE_SYSTEM    IS 'Source system identifier - always MANUAL for date dimension';
COMMENT ON COLUMN BL_DM.DIM_TIME_DAY.SOURCE_ENTITY    IS 'Source entity identifier - always MANUAL for date dimension';

-- Default / unknown row (SURR_ID = -1)
INSERT INTO BL_DM.DIM_TIME_DAY (
    DATE_SURR_ID,
    DATE_SRC_ID,    FULL_DT,
    DAY_OF_WEEK_NUM, DAY_OF_WEEK_DESC, IS_WEEKEND,
    DAY_OF_MONTH_NUM, WEEK_NUM,
    MONTH_NUM,      MONTH_DESC,
    QUARTER_NUM,    YEAR_NUM,
    TA_INSERT_DT,   SOURCE_SYSTEM,   SOURCE_ENTITY
) VALUES (
    -1,
    'N/A',          '1900-01-01',
    -1,             'N/A',            -1,
    -1,             -1,
    'NA',           'N/A',            -- CHAR(2): 'NA' not 'N/A'
    'N',            'N/A',
    CURRENT_DATE,  'MANUAL',         'MANUAL'
);

-- Populate full date range: 2010-01-01 - 2030-12-31
INSERT INTO BL_DM.DIM_TIME_DAY (
    DATE_SRC_ID,
    FULL_DT,
    DAY_OF_WEEK_NUM,
    DAY_OF_WEEK_DESC,
    IS_WEEKEND,
    DAY_OF_MONTH_NUM,
    WEEK_NUM,
    MONTH_NUM,
    MONTH_DESC,
    QUARTER_NUM,
    YEAR_NUM,
    TA_INSERT_DT,
    SOURCE_SYSTEM,
    SOURCE_ENTITY
)
SELECT
    TO_CHAR(d.dt, 'YYYYMMDD')                                       AS DATE_SRC_ID,
    d.dt                                                             AS FULL_DT,
    EXTRACT(ISODOW  FROM d.dt)::INTEGER                              AS DAY_OF_WEEK_NUM,
    TO_CHAR(d.dt, 'Day')                                             AS DAY_OF_WEEK_DESC,
    CASE WHEN EXTRACT(ISODOW FROM d.dt) IN (6,7) THEN 1 ELSE 0 END  AS IS_WEEKEND,
    EXTRACT(DAY     FROM d.dt)::INTEGER                              AS DAY_OF_MONTH_NUM,
    EXTRACT(WEEK    FROM d.dt)::INTEGER                              AS WEEK_NUM,
    TO_CHAR(d.dt, 'MM')                                              AS MONTH_NUM,
    TO_CHAR(d.dt, 'Month')                                           AS MONTH_DESC,
    EXTRACT(QUARTER FROM d.dt)::CHAR(1)                              AS QUARTER_NUM,
    TO_CHAR(d.dt, 'YYYY')                                            AS YEAR_NUM,
    CURRENT_DATE                                                     AS TA_INSERT_DT,
    'MANUAL'                                                         AS SOURCE_SYSTEM,
    'MANUAL'                                                         AS SOURCE_ENTITY
FROM (
    SELECT GENERATE_SERIES(
        '2010-01-01'::DATE,
        '2040-12-31'::DATE,
        INTERVAL '1 day'
    )::DATE AS dt
) d
WHERE NOT EXISTS (
    SELECT 1
    FROM   BL_DM.DIM_TIME_DAY t
    WHERE  t.DATE_SRC_ID = TO_CHAR(d.dt, 'YYYYMMDD')
);

-- Verification
SELECT
    COUNT(*)        AS total_rows,
    MIN(FULL_DT)    AS first_date,
    MAX(FULL_DT)    AS last_date,
    SUM(IS_WEEKEND) AS weekend_days
FROM BL_DM.DIM_TIME_DAY
WHERE DATE_SURR_ID > 0;  -- exclude -1 default row