-- ============================================================
-- DDL - BL_CL Metadata: ETL Execution Log Table
-- NOTE:
--   No default row (-1) required — this is a log/audit table,
--   not a dimension. Rows are append-only; never updated.
-- ============================================================


-- ============================================================
-- 1. SEQUENCE
-- ============================================================

CREATE SEQUENCE IF NOT EXISTS bl_cl.seq_mta_load_logs
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    NO MAXVALUE
    CACHE 1;

COMMENT ON SEQUENCE bl_cl.seq_mta_load_logs IS
    'Surrogate key generator for bl_cl.mta_load_logs. '
    'One value consumed per ETL procedure execution logged.';


-- ============================================================
-- 2. TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS bl_cl.mta_load_logs (

    -- ── Surrogate key ────────────────────────────────────────
    log_id              BIGINT          NOT NULL
                            DEFAULT nextval('bl_cl.seq_mta_load_logs'),

    -- ── When the procedure ran ────────────────────────────────
    ta_log_dt           TIMESTAMP       NOT NULL
                            DEFAULT CURRENT_TIMESTAMP,

    -- ── Which procedure ran ───────────────────────────────────
    procedure_name      VARCHAR(200)    NOT NULL,

    -- ── Row-level statistics ──────────────────────────────────
    rows_inserted       INTEGER         NOT NULL    DEFAULT 0,
    rows_updated        INTEGER         NOT NULL    DEFAULT 0,

    -- ── Outcome ───────────────────────────────────────────────
    -- 'SUCCESS' = procedure completed without exception
    -- 'ERROR'   = procedure caught WHEN OTHERS and re-raised
    status              VARCHAR(10)     NOT NULL,

    -- ── Error detail (NULL on SUCCESS) ────────────────────────
    message             TEXT,

    -- ── Source triplet (optional context for cross-layer logs) ─
    -- Populated when meaningful; defaults to 'n/a' otherwise.
    source_system       VARCHAR(100)    NOT NULL    DEFAULT 'n/a',
    source_entity       VARCHAR(100)    NOT NULL    DEFAULT 'n/a',

    -- ── Constraints ───────────────────────────────────────────
    CONSTRAINT pk_mta_load_logs
        PRIMARY KEY (log_id),

    CONSTRAINT chk_mta_load_logs_status
        CHECK (status IN ('SUCCESS', 'ERROR')),

    CONSTRAINT chk_mta_load_logs_rows_inserted
        CHECK (rows_inserted >= 0),

    CONSTRAINT chk_mta_load_logs_rows_updated
        CHECK (rows_updated >= 0)
);

-- ── Table comment ────────────────────────────────────────────
COMMENT ON TABLE  bl_cl.mta_load_logs IS
    'Central ETL audit log. '
    'One row per procedure execution (SUCCESS or ERROR). '
    'Written by bl_cl.prc_log_procedure() — called from every '
    'prc_load_* and prc_master_load_* procedure in bl_cl. '
    'Append-only — rows are never updated or deleted. '
    'No default row (-1) required (audit table, not a dimension).';

-- ── Column comments ───────────────────────────────────────────
COMMENT ON COLUMN bl_cl.mta_load_logs.log_id IS
    'Surrogate PK — generated by bl_cl.seq_mta_load_logs.';
COMMENT ON COLUMN bl_cl.mta_load_logs.ta_log_dt IS
    'Technical: exact timestamp when this log row was inserted '
    '(= when the procedure call completed or failed). '
    'TA_ prefix per technical attribute naming convention.';
COMMENT ON COLUMN bl_cl.mta_load_logs.procedure_name IS
    'Fully qualified procedure name that wrote this log row. '
    'Example: prc_load_ce_store_zones, prc_master_load_bl3nf.';
COMMENT ON COLUMN bl_cl.mta_load_logs.rows_inserted IS
    'Number of rows inserted by the procedure in this execution. '
    '0 on ERROR or when no new rows were found (idempotent re-run).';
COMMENT ON COLUMN bl_cl.mta_load_logs.rows_updated IS
    'Number of rows updated by the procedure in this execution. '
    'Relevant for SCD Type 1 procedures. 0 for SCD0 / fact loads.';
COMMENT ON COLUMN bl_cl.mta_load_logs.status IS
    'Execution outcome. SUCCESS = completed normally. '
    'ERROR = WHEN OTHERS exception caught; see message column.';
COMMENT ON COLUMN bl_cl.mta_load_logs.message IS
    'NULL on SUCCESS. SQLERRM text on ERROR. '
    'May also carry informational messages on SUCCESS '
    '(e.g. "0 rows — idempotent re-run, data already loaded").';
COMMENT ON COLUMN bl_cl.mta_load_logs.source_system IS
    'Source system context: SA_RETAIL / SA_ECOM / BL_3NF / n/a. '
    'n/a for master orchestration procedures.';
COMMENT ON COLUMN bl_cl.mta_load_logs.source_entity IS
    'Source entity context: SRC_RETAIL_SALES / SRC_ECOM_SALES / n/a.';


-- ============================================================
-- 3. PERFORMANCE INDEX
--    Supports common monitoring queries:
--    - "show me last N executions of a given procedure"
--    - "show me all ERRORs in the last 24h"
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_mta_load_logs_proc_dt
    ON bl_cl.mta_load_logs (procedure_name, ta_log_dt DESC);

CREATE INDEX IF NOT EXISTS idx_mta_load_logs_status_dt
    ON bl_cl.mta_load_logs (status, ta_log_dt DESC)
    WHERE status = 'ERROR';

COMMENT ON INDEX bl_cl.idx_mta_load_logs_proc_dt IS
    'Supports: SELECT ... WHERE procedure_name = ? ORDER BY ta_log_dt DESC.';
COMMENT ON INDEX bl_cl.idx_mta_load_logs_status_dt IS
    'Partial index — ERROR rows only. '
    'Supports fast error monitoring queries.';


