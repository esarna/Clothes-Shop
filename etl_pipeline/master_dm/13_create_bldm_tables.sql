-- DDL - All BL_DM DIM_ and FCT_ tables
-- ============================================================
-- DDL - Create all Dimensional Model (DIM_ and FCT_) tables
-- for the Clothes Shop DWH in the BL_DM schema.
--
--
-- FK CONSTRAINT RULES:
--   DB-level FK enforced from FCT_SALES_DD to:
--     DIM_TIME_DAY      (DATE_SURR_ID)
--     DIM_EMPLOYEES     (EMPLOYEE_SURR_ID)
--     DIM_STORES        (STORE_SURR_ID)
--     DIM_PAYMENT_TYPES (PAYMENT_TYPE_SURR_ID)
--   LOGICAL FK only (no DB constraint) from FCT_SALES_DD to:
--     DIM_CUSTOMERS_SCD (CUSTOMER_SURR_ID)
--     DIM_PRODUCTS_SCD  (PRODUCT_SURR_ID)
--
-- FCT_UNIT_COST NOTE:
--   cost is treated as a monetary value for BOTH sources
--   (retail and ecom).
--
-- TABLE CREATION ORDER (dependency-safe for FK constraints):
--   Group 1 - SCD Type 0 (no FKs to other DIM tables):
--     DIM_TIME_DAY
--     DIM_PAYMENT_TYPES
--   Group 2 - SCD Type 1 (no FKs to other DIM tables):
--     DIM_EMPLOYEES
--     DIM_STORES
--   Group 3 - SCD Type 2 (no FKs to other DIM tables):
--     DIM_CUSTOMERS_SCD
--     DIM_PRODUCTS_SCD
--   Group 4 - Fact table (FKs to all DIM tables above):
--     FCT_SALES_DD
--
-- ============================================================


-- ============================================================
-- GROUP 1 - SCD TYPE 0: Immutable reference tables
--           Rows inserted once and NEVER modified.
--           → No TA_UPDATE_DT column.
--           → SOURCE_SYSTEM = 'MANUAL', SOURCE_ENTITY = 'MANUAL'
--              for default and static reference rows.
-- ============================================================

-- ------------------------------------------------------------
-- 1.1  DIM_TIME_DAY
--      SCD Type 0 - Calendar dimension.
--      NK:  DATE_SRC_ID = YYYYMMDD (VARCHAR(8))
--      Source: bl_3nf.ce_dates
--      No FK dependencies to other DIM tables.
--      No TA_UPDATE_DT - immutable rows.
