-- ============================================================
-- GROUP 4 - FACT TABLE: FCT_SALES_DD
--           Append-only incremental load (no SCD).
--           NO default row.
--           Grain: one product line item per sales transaction.
--
--           FK RULES:
--           • DB-level FK to SCD Type 0 / 1 dimensions:
--               DIM_TIME_DAY, DIM_EMPLOYEES,
--               DIM_STORES, DIM_PAYMENT_TYPES
--           • LOGICAL FK ONLY (no DB constraint) to SCD Type 2:
--               DIM_CUSTOMERS_SCD, DIM_PRODUCTS_SCD
--
--           KPI COLUMNS (nullable by design):
--             FCT_SALES_AMOUNT, FCT_DISCOUNT, FCT_NET_AMOUNT,
--             FCT_UNIT_COST, FCT_QUANTITY,
--             FCT_TOTAL_COST, FCT_GROSS_PROFIT
--
--           DERIVED STORED METRICS:
--             FCT_NET_AMOUNT:
--               RETAIL: FCT_SALES_AMOUNT - FCT_DISCOUNT
--               ECOM:   FCT_SALES_AMOUNT (discount already applied
--                       - do NOT subtract again)
--             FCT_TOTAL_COST:
--               FCT_UNIT_COST × FCT_QUANTITY
--             FCT_GROSS_PROFIT:
--               FCT_NET_AMOUNT - FCT_TOTAL_COST
--
--           FCT_UNIT_COST:
--               Monetary value for BOTH retail and ecom sources.
--
--           LINE_SRC_ID (degenerate dimension):
--               Unique line identifier per grain.
--               Composed as: PAYMENT_SRC_ID || '_' || PRODUCT_SRC_ID
-- ============================================================

DROP TABLE IF EXISTS bl_dm.fct_sales_dd CASCADE;
ALTER SEQUENCE IF EXISTS bl_dm.seq_fct_sales_dd RESTART WITH 1;

CREATE TABLE bl_dm.fct_sales_dd (
    sales_surr_id           BIGINT          NOT NULL    DEFAULT nextval('bl_dm.seq_fct_sales_dd'),
    event_dt                DATE            NOT NULL,
    date_surr_id            BIGINT          NOT NULL,
    customer_surr_id        BIGINT          NOT NULL,
    employee_surr_id        BIGINT          NOT NULL,
    product_surr_id         BIGINT          NOT NULL,
    store_surr_id           BIGINT          NOT NULL,
    payment_type_surr_id    BIGINT          NOT NULL,
    payment_src_id          VARCHAR(50)     NOT NULL,
    line_src_id             VARCHAR(100)    NOT NULL,
    fct_sales_amount        DECIMAL(12,2),
    fct_discount            DECIMAL(12,2),
    fct_net_amount          DECIMAL(12,2),
    fct_unit_cost           DECIMAL(12,2),
    fct_quantity            INTEGER,
    fct_total_cost          DECIMAL(12,2),
    fct_gross_profit        DECIMAL(12,2),
    ta_insert_dt            DATE            NOT NULL,
    ta_update_dt            DATE            NOT NULL,
    source_system           VARCHAR(50)     NOT NULL,
    source_entity           VARCHAR(50)     NOT NULL,
    CONSTRAINT pk_fct_sales_dd              PRIMARY KEY (sales_surr_id),
    -- Grain uniqueness: one product line item per transaction per source
    CONSTRAINT uq_fct_sales_dd_grain        UNIQUE      (line_src_id, source_system),
    -- DB-level FK constraints to SCD Type 0 / 1 dimensions:
    CONSTRAINT fk_fct_sales_dd_date         FOREIGN KEY (date_surr_id)
                                            REFERENCES  bl_dm.dim_time_day      (date_surr_id),
    CONSTRAINT fk_fct_sales_dd_employee     FOREIGN KEY (employee_surr_id)
                                            REFERENCES  bl_dm.dim_employees     (employee_surr_id),
    CONSTRAINT fk_fct_sales_dd_store        FOREIGN KEY (store_surr_id)
                                            REFERENCES  bl_dm.dim_stores        (store_surr_id),
    CONSTRAINT fk_fct_sales_dd_payment_type FOREIGN KEY (payment_type_surr_id)
                                            REFERENCES  bl_dm.dim_payment_types (payment_type_surr_id),
    CONSTRAINT chk_fct_sales_dd_quantity CHECK (fct_quantity IS NULL OR fct_quantity >= 0)
    -- NOTE: FK to DIM_CUSTOMERS_SCD (customer_surr_id) and
    --       DIM_PRODUCTS_SCD (product_surr_id) are LOGICAL ONLY.
);

