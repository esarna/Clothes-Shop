DROP TABLE IF EXISTS bl_dm.dim_time_day CASCADE;
ALTER SEQUENCE IF EXISTS bl_dm.seq_dim_time_day RESTART WITH 1;

CREATE TABLE bl_dm.dim_time_day (
    date_surr_id        BIGINT          NOT NULL    DEFAULT nextval('bl_dm.seq_dim_time_day'),
    date_src_id         VARCHAR(8)      NOT NULL,
    full_dt             DATE            NOT NULL,
    day_of_week_num     INTEGER         NOT NULL,
    day_of_week_desc    VARCHAR(25)     NOT NULL,
    is_weekend          INTEGER         NOT NULL,
    day_of_month_num    INTEGER         NOT NULL,
    week_num            INTEGER         NOT NULL,
    month_num           VARCHAR(3)      NOT NULL,
